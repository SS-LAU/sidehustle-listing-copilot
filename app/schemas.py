"""Pydantic models: define the API request/response shapes and the Listing structure."""
from __future__ import annotations

from typing import Optional

from pydantic import BaseModel, Field


class GenerateRequest(BaseModel):
    """Generation request sent by the frontend."""

    keywords: str = Field(..., min_length=1, description="Product keywords, comma-separated")
    platform: str = Field(default="Etsy", description="Marketplace: Etsy or eBay")
    tone: str = Field(default="friendly", description="Brand tone: friendly / professional / playful / luxury")


class Listing(BaseModel):
    """Structured listing copy generated by Ollama."""

    title: str = Field(..., description="Product title")
    description: str = Field(..., description="Product description")
    tags: list[str] = Field(default_factory=list, description="Search tags")


class PriceStats(BaseModel):
    """Competitor price statistics (SerpApi add-on; None when no API key is set)."""

    min: Optional[float] = None
    max: Optional[float] = None
    median: Optional[float] = None
    count: int = 0


class SaveRequest(BaseModel):
    """Frontend sends back a generated listing to be saved."""

    title: str = Field(..., min_length=1)
    description: str = Field(default="")
    tags: list[str] = Field(default_factory=list)


class GenerateResponse(BaseModel):
    """API response: generated copy + optional competitor prices + optional saved id."""

    listing: Listing
    price_stats: Optional[PriceStats] = None
    saved_id: Optional[str] = None
    elapsed_sec: Optional[float] = None
    model: Optional[str] = None
    error: Optional[str] = None
